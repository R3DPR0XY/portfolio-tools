    private static String[] filterSafeTokens(String[] source) {
        Set<String> unique = new LinkedHashSet<>();
        for (String token : source) {
            if (isLikelyRenderable(token)) {
                unique.add(token);
            }
        }
        return unique.toArray(String[]::new);
    }

    private static boolean isLikelyRenderable(String token) {
        if (token == null || token.isBlank()) {
            return false;
        }

        int count = token.codePointCount(0, token.length());
        if (count != 1) {
            return false;
        }

        int codePoint = token.codePointAt(0);
        if (codePoint > 0xFFFF) {
            return false;
        }

        int type = Character.getType(codePoint);
        if (type == Character.UNASSIGNED
            || type == Character.SURROGATE
            || type == Character.PRIVATE_USE
            || type == Character.FORMAT
            || type == Character.NON_SPACING_MARK
            || type == Character.COMBINING_SPACING_MARK
            || type == Character.ENCLOSING_MARK) {
            return false;
        }

        return !Character.isISOControl(codePoint);
    }
